import numpy as np

from utils.hjb import HJBSubsolutionLP


class HJBCertificateBound:
    """Сертифицированная граница через субрешение уравнения Беллмана.

    В отличие от геометрических методов, эта оценка не опирается на
    вложение множеств управлений, а строит явный сертификат: функцию W,
    удовлетворяющую дифференциальному неравенству

        <W_x, y> - ||W_y|| + (1/2)||x||^2 >= 0,   W(0, 0) = 0,

    из которого стандартным рассуждением о верификации следует W <= J*.
    Анзац W = ||y||^5 f(p, q), согласованный с фуллеровской и вращательной
    симметриями, сводит неравенство к соотношению на плоскости инвариантов.
    Дискретизация f по сетке и линеаризация нормы через опорные направления
    превращают задачу в линейное программирование, максимизирующее интеграл
    от f, то есть выбирающее самый тугой сертификат в заданном классе.

    Преимущество метода в том, что полученная граница доказана, а не
    получена подстановкой конкретной допустимой траектории, и её точность
    систематически повышается измельчением сетки.
    """

    def __init__(self, **lp_kwargs):
        """
        Args:
            lp_kwargs: параметры дискретизации, передаются в HJBSubsolutionLP.
        """
        self.lp = HJBSubsolutionLP(**lp_kwargs)
        self._sol = None

    def fit(self):
        """Построение сертификата решением задачи линейного программирования."""
        self._sol = self.lp.solve()
        return self._sol

    def lower_bound_hjb(self, x, y):
        """Значение сертифицированной границы в точке (x, y).

        При первом вызове автоматически строится сертификат.
        """
        if self._sol is None:
            self.fit()
        if not self._sol["success"]:
            return -np.inf
        return HJBSubsolutionLP.evaluate(self._sol, x, y)
    